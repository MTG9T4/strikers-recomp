    config = os.path.join(folder, 'CMakeLists.txt')
    if not os.path.exists(config) or open(config).read() != source:
        open(config, 'w', newline='\n').write(source)
    dll = os.path.join(folder, 'msvc', 'Release', 'strikers_zt.dll')
    inputs = [config, rel('runtime/services/zt_group_filter.h')] + [os.path.join(folder, name) for name in ('NodeService.cpp', 'VirtualTap.cpp', 'lwipopts.h', 'Network.cpp')]
